/** Exercise workspace reference completion, navigation and backlinks through actual Rivto paragraphs. */
import {chromium,firefox,expect} from '@playwright/test'
import {mkdtemp,rm} from 'node:fs/promises'
import {tmpdir} from 'node:os'
import {join,resolve} from 'node:path'
import {serve} from '../../src/server/service'

const dir=await mkdtemp(join(tmpdir(),'chulane-refs-'))
const host=await serve({file:join(dir,'test.sqlite'),assets:resolve('dist'),registration:true})
const browser=await (process.env.CHULANE_TEST_BROWSER==='firefox'?firefox:chromium).launch()
try{
  const page=await browser.newPage()
  /** Create fixtures through the same authorized endpoints as the library. */
  async function post(path:string,data:object){
    const response=await page.request.post(host.url+'/api/'+path,{data})
    expect(response.ok(),await response.text()).toBe(true)
    return response.json()
  }
  await post('register',{username:'writer',password:'another-passphrase'})
  const {id:ws}=await post('workspaces',{name:'Research'})
  const scope='?workspace='+ws
  const target=await post('pages'+scope,{title:'Field notes'})
  const source=await post('pages'+scope,{title:'Index'})
  const diagram=await post('pages'+scope,{title:'Harbor diagram'})
  const field=page.locator('article.doc:visible [data-block-content]').first()
  const links=async(id:number,direction:string)=>(await(await page.request.get(host.url+'/api/pages/'+id+'/links'+scope+'&direction='+direction)).json()).entries.map((row:{id:number})=>row.id)
  const chart=scope+'&page='+diagram.id+'&view=canvas'
  const fieldNotes=scope+'&page='+target.id
  const imported=await post('pages/import-markdown'+scope,{title:'Pilot guide',content:[
    'See [harbor map][CHART] or [chart][].','',
    '[chart]: '+chart,'[CHART]: '+fieldNotes,'[unused]: '+fieldNotes,'',
    '![Legend][image]','','[image]: '+fieldNotes,
  ].join('\n')})
  await page.goto(host.url+'/'+scope+'&page='+imported.id)
  const mapLink=page.locator('article.doc:visible .markdown-preview').getByRole('link',{name:'harbor map'})
  await expect(mapLink).toHaveAttribute('href',chart)
  expect(await links(imported.id,'outgoing')).toEqual([diagram.id])
  expect(await links(target.id,'incoming')).not.toContain(imported.id)
  await expect(page.getByRole('navigation',{name:'Inline references'}).getByRole('link')).toHaveCount(1)
  await mapLink.press('Enter')
  await expect(page.getByRole('radio',{name:'Canvas',exact:true})).toHaveAttribute('aria-checked','true')
  await page.getByRole('navigation',{name:'Referenced by'}).getByRole('link',{name:'Pilot guide'}).click()
  await expect(page.getByRole('heading',{name:'Pilot guide',exact:true})).toBeVisible()
  await field.fill('Route retired.\n\n[chart]: '+chart)
  await page.getByRole('button',{name:'Save now'}).click()
  await expect.poll(()=>links(diagram.id,'incoming')).not.toContain(imported.id)
  // A pasted workspace URL follows the same GFM autolink rules as the rendered writing.
  const pasted=host.url+'/'+scope+'&page='+diagram.id+'&view=canvas'
  const external='https://example.org/'+scope+'&page='+target.id
  const literal=host.url+'/'+scope+'&page='+target.id
  const pastedSource=await post('pages'+scope,{title:'Survey handoff',content:'Open ('+pasted+'). Outside: '+external+' Code: `'+literal+'`'})
  await page.goto(host.url+'/'+scope+'&page='+pastedSource.id)
  const autolink=page.locator('article.doc:visible .markdown-preview').getByRole('link',{name:pasted,exact:true})
  await expect(autolink).toHaveAttribute('href',pasted)
  expect(await links(pastedSource.id,'outgoing')).toEqual([diagram.id])
  expect(await links(diagram.id,'incoming')).toContain(pastedSource.id)
  await expect(page.getByRole('navigation',{name:'Inline references'}).getByRole('link',{name:'Harbor diagram · Canvas'})).toHaveAttribute('href',scope+'&page='+diagram.id+'&view=canvas')
  await autolink.click()
  await expect(page.getByRole('radio',{name:'Canvas',exact:true})).toHaveAttribute('aria-checked','true')
  await page.getByRole('navigation',{name:'Referenced by'}).getByRole('link',{name:'Survey handoff'}).click()
  await expect(page.getByRole('heading',{name:'Survey handoff',exact:true})).toBeVisible()
  await field.fill('Handoff complete')
  await page.getByRole('navigation',{name:'Library',exact:true}).getByRole('button',{name:'Index',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Index',exact:true})).toBeVisible()
  await expect.poll(()=>links(diagram.id,'incoming')).not.toContain(pastedSource.id)
  await page.goto(host.url+'/'+scope+'&page='+target.id)
  await field.fill('Rare tidal finding')
  await page.getByRole('button',{name:'Save now'}).click()
  const block=await field.evaluate(node=>node.closest('[data-block-id]')!.getAttribute('data-block-id'))
  await page.getByRole('navigation',{name:'Library',exact:true}).getByRole('button',{name:'Index',exact:true}).click()
  await field.click()
  await page.keyboard.type('#tidal-tag')
  const assigned=page.waitForResponse(response=>response.request().method()==='PUT'&&new URL(response.url()).pathname.endsWith('/tags'))
  await page.keyboard.press('Enter')
  expect((await assigned).ok()).toBe(true)
  // Complete in the middle of prose, keeping closing punctuation and the insertion point.
  await field.fill('Survey ()')
  await field.press('End')
  await field.press('ArrowLeft')
  await page.keyboard.type('#tid')
  await expect(page.getByRole('listbox',{name:'Workspace tags'}).getByRole('option',{name:'#tidal-tag',exact:true})).toBeVisible()
  await field.press('Enter')
  await expect(field).toHaveText('Survey (#tidal-tag)')
  await page.keyboard.type('!')
  await expect(field).toHaveText('Survey (#tidal-tag!)')
  await field.fill('See:[[Field]].')
  await field.press('Home')
  for(let i=0;i<'See:[['.length;i++)await field.press('ArrowRight')
  await page.keyboard.type('Field no')
  await expect(page.getByRole('listbox',{name:'Page references'}).getByRole('option',{name:'Field notes',exact:true})).toBeVisible()
  await field.press('Enter')
  await expect(field).toHaveText('See:[[Field notes]].')
  await page.keyboard.type('!')
  await expect(field).toHaveText('See:[[Field notes]]!.')
  for(const literal of ['escaped \\#tid','word#tid','https://example.org/?q=#tid','[Field notes](#tid','![Map #tid','![Field no','escaped \\[Field no']){
    await field.fill(literal.slice(0,-1))
    await field.press('End')
    await page.keyboard.type(literal.slice(-1))
    await expect(page.getByRole('listbox',{name:/Workspace tags|Page references/})).toHaveCount(0)
  }
  await field.fill('[Field n](https://example.org)')
  await field.press('Home')
  for(let i=0;i<'[Field n'.length;i++)await field.press('ArrowRight')
  await page.keyboard.type('o')
  await expect(page.getByRole('listbox',{name:'Page references'})).toHaveCount(0)
  await expect(field).toHaveText('[Field no](https://example.org)')
  await field.fill('#tidal-tag ')
  await field.press('End')
  await page.keyboard.type('#')
  await expect(page.getByRole('listbox',{name:'Workspace tags'}).getByRole('option',{name:'#tidal-tag'})).toBeVisible()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Backspace')
  await page.keyboard.type('[Field notes]')
  await expect(field).toContainText('[Field notes]')
  await page.keyboard.type('(https://example.org/field) [Field notes] ')
  await page.keyboard.type('[[Field no')
  await page.getByRole('option',{name:'Field notes',exact:true}).click()
  await page.keyboard.type('[[Field notes]] ')
  await page.keyboard.type('((Rare tidal')
  await expect(page.getByRole('listbox',{name:'Block references'}).getByRole('option',{name:/Field notes.*Rare tidal finding/})).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(field).toContainText('block='+block)
  await page.keyboard.type('[Fresh destination] #automatic [Saved canvas](?page='+target.id+'&view=canvas&workspace='+ws+') [Harbor canvas]('+host.url+'/'+scope+'&page='+diagram.id+'&view=canvas)')
  const inline=page.locator('article.doc:visible .surface-body')
  await inline.click({position:{x:4,y:12}})
  await expect(inline.getByRole('link',{name:'Field notes',exact:true}).first()).toHaveAttribute('href','https://example.org/field')
  await expect(inline.locator('a').filter({hasText:'Field notes'})).toHaveCount(4)
  await expect(inline.getByRole('link',{name:'#automatic',exact:true})).toBeVisible()
  await inline.getByRole('link',{name:'[Fresh destination]',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Fresh destination',exact:true})).toBeVisible()
  await page.getByRole('navigation',{name:'Library',exact:true}).getByRole('button',{name:'Index',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Index',exact:true})).toBeVisible()
  const tagButton=page.getByRole('button',{name:'Page tags',exact:true})
  await tagButton.click()
  const picker=page.getByRole('dialog',{name:'Page tags',exact:true})
  await expect(picker.getByRole('combobox')).toHaveCount(0)
  const pageTag=picker.getByRole('checkbox',{name:'#automatic',exact:true})
  await expect(pageTag).not.toBeChecked()
  await pageTag.check()
  await expect(page.getByRole('button',{name:'#automatic',exact:true})).toBeVisible()
  await pageTag.uncheck()
  await expect(page.getByRole('button',{name:'#automatic',exact:true})).toHaveCount(0)
  await page.keyboard.press('Escape')
  await inline.getByRole('link',{name:'#automatic',exact:true}).click()
  await expect(page.getByRole('heading',{name:'#automatic',exact:true}).first()).toBeVisible()
  await page.locator('[data-part="tag-sources"]').getByRole('link',{name:/Index/}).click()
  await page.getByRole('heading',{name:'Index',exact:true}).click()
  await inline.getByRole('link',{name:'Rare tidal finding'}).click()
  await expect(page.getByRole('heading',{name:'Field notes',exact:true})).toBeVisible()
  await expect.poll(()=>new URL(page.url()).searchParams.get('block')).toBe(block)
  await page.reload()
  await page.getByRole('heading',{name:'Field notes',exact:true}).press('F2')
  const name=page.getByRole('form',{name:'Rename page'}).getByLabel('Name')
  await name.fill('Tidal notes');await name.press('Enter')
  await expect(page.getByRole('heading',{name:'Tidal notes',exact:true})).toBeVisible()
  await page.getByRole('navigation',{name:'Referenced by'}).getByRole('link',{name:'Index'}).click()
  await expect(page.getByRole('heading',{name:'Index',exact:true})).toBeVisible()
  const outgoing=page.getByRole('navigation',{name:'Inline references'})
  await expect(outgoing.getByRole('link',{name:'Tidal notes',exact:true})).toHaveAttribute('href',scope+'&page='+target.id)
  await expect(outgoing.getByRole('link',{name:/Tidal notes · Rare tidal/})).toHaveAttribute('href',scope+'&page='+target.id+'&block='+block)
  const viewer=await browser.newPage()
  const registration=await viewer.request.post(host.url+'/api/register',{data:{username:'reader',password:'another-passphrase'}})
  expect(registration.ok()).toBe(true)
  const invite=await post('workspaces/invitations'+scope,{username:'reader',role:'viewer'})
  expect((await viewer.request.post(host.url+'/api/invitations/'+invite.id+'/accept')).ok()).toBe(true)
  await viewer.goto(host.url+'/'+scope+'&page='+source.id)
  const readerLink=viewer.locator('.doc:visible .markdown-preview').getByRole('link',{name:'[Field notes]',exact:true})
  await expect(viewer.locator('article.doc:visible [data-block-content]').first()).toHaveAttribute('inert','')
  await readerLink.focus()
  await expect(readerLink).toBeFocused()
  await readerLink.press('Enter')
  await expect(viewer.getByRole('heading',{name:'Tidal notes',exact:true})).toBeVisible()
  await viewer.goto(host.url+'/'+scope+'&page='+source.id)
  await viewer.getByRole('navigation',{name:'Inline references'}).getByRole('link',{name:/Tidal notes · Rare tidal/}).click()
  await expect.poll(()=>new URL(viewer.url()).searchParams.get('block')).toBe(block)
  await expect(viewer.getByRole('heading',{name:'Tidal notes',exact:true})).toBeVisible()
  await viewer.goto(host.url+'/'+scope+'&page='+source.id)
  const readerPreview=viewer.locator('article.doc:visible .markdown-preview')
  const copied=await readerPreview.getByRole('link',{name:'[Field notes]',exact:true}).getAttribute('href')
  await viewer.goto(new URL(copied!,host.url).href)
  await expect(viewer.getByRole('heading',{name:'Tidal notes',exact:true})).toBeVisible()
  await viewer.goto(host.url+'/'+scope+'&page='+source.id)
  await viewer.route('https://example.org/field',route=>route.fulfill({body:'External destination'}))
  const canvasLink=viewer.getByRole('navigation',{name:'Inline references'}).getByRole('link',{name:'Tidal notes · Canvas',exact:true})
  await expect(canvasLink).toHaveAttribute('href',scope+'&page='+target.id+'&view=canvas')
  await readerPreview.getByRole('link',{name:'Saved canvas',exact:true}).press('Enter')
  await expect(viewer.getByRole('radio',{name:'Canvas',exact:true})).toHaveAttribute('aria-checked','true')
  await expect(viewer.getByRole('tab',{name:/Index/})).toBeVisible()
  await viewer.goto(host.url+'/'+scope+'&page='+source.id)
  const diagramLink=viewer.getByRole('navigation',{name:'Inline references'}).getByRole('link',{name:'Harbor diagram · Canvas',exact:true})
  await diagramLink.press('Enter')
  await expect(viewer.getByRole('heading',{name:'Harbor diagram',exact:true})).toBeVisible()
  await expect(viewer.getByRole('radio',{name:'Canvas',exact:true})).toHaveAttribute('aria-checked','true')
  await viewer.getByRole('navigation',{name:'Referenced by'}).getByRole('link',{name:'Index'}).click()
  await readerPreview.getByRole('link',{name:'Field notes',exact:true}).first().click()
  await expect(viewer).toHaveURL('https://example.org/field')
  await viewer.close()
  await field.fill('References removed')
  await page.getByRole('button',{name:'Save now'}).click()
  await page.getByRole('navigation',{name:'Library',exact:true}).getByRole('button',{name:'Tidal notes',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Tidal notes',exact:true})).toBeVisible()
  await expect(page.getByRole('navigation',{name:'Referenced by'})).toHaveCount(0)
  const notebook=await post('pages/import-markdown'+scope,{title:'Table of tides',content:[
    '| Reference | Fieldwork |','| --- | --- |',String.raw`| [[Harbor diagram]] | #ebb and \#literal |`,'',
    '- [ ] Visit the inlet','  and read [Tidal notes].',
  ].join('\n')})
  const exported=await(await page.request.get(host.url+'/api/pages/'+notebook.id+'/markdown'+scope)).json()
  const copy=await post('pages/import-markdown'+scope,{title:'Restored tides',content:exported.markdown})
  await page.goto(host.url+'/'+scope+'&page='+copy.id)
  const previews=page.locator('article.doc:visible .markdown-preview')
  await expect(previews.getByRole('link',{name:'#ebb',exact:true})).toBeVisible()
  await expect(previews.getByRole('link',{name:'#literal',exact:true})).toHaveCount(0)
  await expect(previews.getByRole('link',{name:'[Tidal notes]',exact:true})).toBeVisible()
  await previews.getByRole('link',{name:'#ebb',exact:true}).press('Enter')
  await expect(page.getByRole('heading',{name:'#ebb',exact:true}).first()).toBeVisible()
  await page.goto(host.url+'/'+scope+'&page='+copy.id)
  await previews.getByRole('link',{name:'[[Harbor diagram]]',exact:true}).press('Enter')
  await expect(page.getByRole('heading',{name:'Harbor diagram',exact:true})).toBeVisible()
  console.log('Reimported table and checklist references rendered and opened their target.')
  console.log('Page and block references, internal navigation and backlink removal passed.')
}finally{await browser.close();await host.close();await rm(dir,{recursive:true,force:true})}
