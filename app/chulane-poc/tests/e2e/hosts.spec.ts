/** Start from the real first-run screen in either host and retain the selected workspace calendar. */
async function firstWorkspace(p:Page,checkRetry=false){
  const form=p.getByRole('form',{name:'Create workspace'})
  await expect(p.getByRole('heading',{name:'Create your first workspace'})).toBeVisible()
  await expect(form.getByRole('button',{name:'Create workspace'})).toBeDisabled()
  await form.getByLabel('Workspace name').fill('Field library')
  await form.getByLabel('Workspace time zone').selectOption('Europe/London')
  if(checkRetry){
    const endpoint=(url:URL)=>url.pathname==='/api/workspaces'
    let attempts=0
    await p.route(endpoint,route=>{
      if(route.request().method()!=='POST')return route.continue()
      attempts++
      return route.fulfill({status:503,json:{error:'Workspace storage unavailable'}})
    })
    await form.evaluate((node:HTMLFormElement)=>{node.requestSubmit();node.requestSubmit()})
    await expect(p.getByRole('alert')).toHaveText('Workspace storage unavailable')
    await expect(form.getByLabel('Workspace name')).toHaveValue('Field library')
    await expect(form.getByLabel('Workspace time zone')).toHaveValue('Europe/London')
    expect(attempts).toBe(1)
    await p.unroute(endpoint)
  }
  await form.getByRole('button',{name:'Create workspace'}).click()
  await expect(p.getByLabel('Workspace',{exact:true})).toHaveValue('1')
}
/** Paste a binary clipboard item into an empty Rivto block and wait for its durable page attachment. */
async function pasteFieldSample(p:Page){
  const paragraph=p.locator('[data-block-content]').last()
  await paragraph.press('End')
  await paragraph.press('Enter')
  const field=p.locator('[data-block-content]').last()
  await expect(field).toHaveText('')
  await field.click()
  await field.evaluate(element=>{
    const clipboardData=new DataTransfer()
    clipboardData.setData('text/plain','/field/photo.png')
    element.dispatchEvent(new ClipboardEvent('paste',{clipboardData,bubbles:true,cancelable:true}))
  })
  await expect(field).toHaveText('/field/photo.png')
  await field.press('End')
  await field.press('Enter')
  await expect(field).toHaveText('')
  await field.evaluate(element=>{
    const clipboardData=new DataTransfer()
    clipboardData.items.add(new File([Uint8Array.of(0,255,37,0,162)],'sample.opaque',{type:'application/octet-stream'}))
    element.dispatchEvent(new ClipboardEvent('paste',{clipboardData,bubbles:true,cancelable:true}))
  })
  await expect(p.getByRole('button',{name:'Open file sample.opaque'})).toBeVisible()
  await expect(p.getByRole('link',{name:'sample.opaque',exact:true})).toBeVisible()
}
