/** Check the reopened drawing and the saved connector bindings against the original shape IDs. */
async function expectMapBoundary(p:Page,boundary:MapBoundary){
  const shape=p.locator('[data-edgeless-object-id="'+boundary.rectangle+'"]')
  await expect(shape.locator('rect').first()).toHaveAttribute('fill','#275d67')
  const stroke=p.locator('[data-edgeless-object-id="'+boundary.stroke+'"] .edgeless-drawing-stroke')
  await expect(stroke).toHaveAttribute('d',boundary.path)
  const connector=p.locator('[data-edgeless-object-id="'+boundary.connector+'"]')
  await expect(connector.locator('.edgeless-connector')).toHaveAttribute('data-edgeless-connector-route','straight')
  const page=await p.locator('article.doc').getAttribute('data-source-page')
  const workspace=await p.getByLabel('Workspace',{exact:true}).inputValue()
  const bytes=await p.evaluate(async path=>{
    const response=await fetch(path)
    if(!response.ok)throw Error('Cannot read persisted canvas')
    return Array.from(new Uint8Array(await response.arrayBuffer()))
  },'/api/pages/'+page+'/state?workspace='+workspace)
  const doc=new Y.Doc(),model=new DocumentModelImpl(new YjsDoc('canvas-reopen',doc))
  try{
    Y.applyUpdate(doc,Uint8Array.from(bytes))
    expect(model.elements.getElementNode(boundary.connector)?.props).toMatchObject({
      source:{elementId:boundary.rectangle},target:{elementId:boundary.ellipse}
    })
  }finally{await model.destroy()}
}
